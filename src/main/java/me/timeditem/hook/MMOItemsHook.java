package me.timeditem.hook;

import me.timeditem.TimedItem;
import org.bukkit.Bukkit;
import org.bukkit.inventory.ItemStack;

import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

/**
 * Safe reflection wrapper for MMOItems integration.
 * Prevents NoClassDefFoundError or compile issues whether MMOItems is present or not.
 */
public class MMOItemsHook {
    private final TimedItem plugin;

    public MMOItemsHook(TimedItem plugin) {
        this.plugin = plugin;
    }

    public boolean isAvailable() {
        return Bukkit.getPluginManager().isPluginEnabled("MMOItems");
    }

    /**
     * Retrieves an ItemStack generated by MMOItems by Type and ID.
     *
     * @param typeName MMOItems type (e.g. SWORD, BOW, ARMOR, CONSUMABLE)
     * @param id       MMOItems ID (e.g. CUTLASS, SILVER_SWORD)
     * @return Generated ItemStack, or null if type/id not found or MMOItems unavailable.
     */
    public ItemStack getItem(String typeName, String id) {
        if (!isAvailable() || typeName == null || id == null) {
            return null;
        }

        try {
            Class<?> mmoItemsClass = Class.forName("net.Indyuce.mmoitems.MMOItems");
            Field pluginField = mmoItemsClass.getField("plugin");
            Object mmoPlugin = pluginField.get(null);
            if (mmoPlugin == null) {
                return null;
            }

            // 1. Resolve Type instance
            Object typeObj = resolveType(mmoPlugin, typeName);
            if (typeObj == null) {
                return null;
            }

            // 2. Try MMOItems.plugin.getItem(Type, String)
            for (Method m : mmoPlugin.getClass().getMethods()) {
                if (m.getName().equals("getItem") && m.getParameterCount() == 2
                        && m.getParameterTypes()[1] == String.class
                        && m.getParameterTypes()[0].isAssignableFrom(typeObj.getClass())) {
                    Object result = m.invoke(mmoPlugin, typeObj, id.toUpperCase());
                    if (result instanceof ItemStack is) {
                        return is.clone();
                    }
                }
            }

            // 3. Fallback: MMOItems.plugin.getMMOItem(Type, id).newBuilder().build()
            for (Method m : mmoPlugin.getClass().getMethods()) {
                if (m.getName().equals("getMMOItem") && m.getParameterCount() == 2
                        && m.getParameterTypes()[1] == String.class
                        && m.getParameterTypes()[0].isAssignableFrom(typeObj.getClass())) {
                    Object mmoItem = m.invoke(mmoPlugin, typeObj, id.toUpperCase());
                    if (mmoItem != null) {
                        Method newBuilderMethod = mmoItem.getClass().getMethod("newBuilder");
                        Object builder = newBuilderMethod.invoke(mmoItem);
                        if (builder != null) {
                            Method buildMethod = builder.getClass().getMethod("build");
                            Object built = buildMethod.invoke(builder);
                            if (built instanceof ItemStack is) {
                                return is.clone();
                            }
                        }
                    }
                }
            }
        } catch (Throwable t) {
            plugin.getLogger().warning("Error generating MMOItem (" + typeName + ":" + id + "): " + t.getMessage());
        }

        return null;
    }

    private Object resolveType(Object mmoPlugin, String typeName) {
        try {
            Method getTypesMethod = mmoPlugin.getClass().getMethod("getTypes");
            Object typesManager = getTypesMethod.invoke(mmoPlugin);
            if (typesManager != null) {
                Method getMethod = typesManager.getClass().getMethod("get", String.class);
                Object typeObj = getMethod.invoke(typesManager, typeName.toUpperCase());
                if (typeObj != null) {
                    return typeObj;
                }
            }
        } catch (Exception ignored) {
        }

        try {
            Method getTypeMethod = mmoPlugin.getClass().getMethod("getType", String.class);
            return getTypeMethod.invoke(mmoPlugin, typeName.toUpperCase());
        } catch (Exception ignored) {
        }

        try {
            Class<?> typeClass = Class.forName("net.Indyuce.mmoitems.api.Type");
            Method getMethod = typeClass.getMethod("get", String.class);
            return getMethod.invoke(null, typeName.toUpperCase());
        } catch (Exception ignored) {
        }

        return null;
    }

    /**
     * Lists all registered MMOItems Types (for tab-completion).
     */
    public List<String> getTypes() {
        if (!isAvailable()) {
            return Collections.emptyList();
        }

        List<String> list = new ArrayList<>();
        try {
            Class<?> mmoItemsClass = Class.forName("net.Indyuce.mmoitems.MMOItems");
            Field pluginField = mmoItemsClass.getField("plugin");
            Object mmoPlugin = pluginField.get(null);
            Method getTypesMethod = mmoPlugin.getClass().getMethod("getTypes");
            Object typesManager = getTypesMethod.invoke(mmoPlugin);
            Method getAllMethod = typesManager.getClass().getMethod("getAll");
            Object collection = getAllMethod.invoke(typesManager);

            if (collection instanceof Iterable<?> iterable) {
                for (Object obj : iterable) {
                    Method getIdMethod = obj.getClass().getMethod("getId");
                    Object id = getIdMethod.invoke(obj);
                    if (id != null) {
                        list.add(id.toString());
                    }
                }
            }
        } catch (Throwable ignored) {
        }
        return list;
    }

    /**
     * Lists registered item template IDs for a given type (for tab-completion).
     */
    public List<String> getTemplateIds(String typeName) {
        if (!isAvailable() || typeName == null) {
            return Collections.emptyList();
        }

        List<String> list = new ArrayList<>();
        try {
            Class<?> mmoItemsClass = Class.forName("net.Indyuce.mmoitems.MMOItems");
            Field pluginField = mmoItemsClass.getField("plugin");
            Object mmoPlugin = pluginField.get(null);
            Object typeObj = resolveType(mmoPlugin, typeName);
            if (typeObj == null) {
                return list;
            }

            Method getTemplatesMethod = mmoPlugin.getClass().getMethod("getTemplates");
            Object templatesManager = getTemplatesMethod.invoke(mmoPlugin);
            for (Method m : templatesManager.getClass().getMethods()) {
                if ((m.getName().equals("getTemplates") || m.getName().equals("collectTemplates"))
                        && m.getParameterCount() == 1
                        && m.getParameterTypes()[0].isAssignableFrom(typeObj.getClass())) {
                    Object result = m.invoke(templatesManager, typeObj);
                    if (result instanceof Iterable<?> iterable) {
                        for (Object template : iterable) {
                            try {
                                Method getIdMethod = template.getClass().getMethod("getId");
                                Object id = getIdMethod.invoke(template);
                                if (id != null) {
                                    list.add(id.toString());
                                }
                            } catch (Exception ignored) {
                            }
                        }
                    }
                    break;
                }
            }
        } catch (Throwable ignored) {
        }
        return list;
    }
}
