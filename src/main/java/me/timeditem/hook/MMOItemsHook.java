package me.timeditem.hook;

import me.timeditem.TimedItem;
import org.bukkit.Bukkit;
import org.bukkit.inventory.ItemStack;

import java.lang.reflect.Field;
import java.lang.reflect.Method;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Cached reflection wrapper for MMOItems integration.
 * Prevents NoClassDefFoundError whether MMOItems is present or not,
 * while caching reflected methods and tab-completion lists to avoid main-thread overhead.
 */
public class MMOItemsHook {
    private final TimedItem plugin;

    // Cached reflection handles
    private volatile boolean initialized = false;
    private Field pluginField;
    private Method getItemMethod;
    private Method getMMOItemMethod;
    private Method getTypesMethod;
    private Method getTemplatesMethod;

    // 30-second cache for tab-completion lists
    private List<String> cachedTypes = Collections.emptyList();
    private long cachedTypesTimestamp = 0L;
    private final Map<String, List<String>> cachedTemplateIds = new ConcurrentHashMap<>();
    private long cachedTemplatesTimestamp = 0L;
    private static final long CACHE_TTL_MS = 30_000L;

    public MMOItemsHook(TimedItem plugin) {
        this.plugin = plugin;
    }

    public boolean isAvailable() {
        return Bukkit.getPluginManager().isPluginEnabled("MMOItems");
    }

    private void ensureInitialized(Object mmoPlugin) {
        if (initialized || mmoPlugin == null) {
            return;
        }
        synchronized (this) {
            if (initialized) {
                return;
            }
            Class<?> pluginClass = mmoPlugin.getClass();
            for (Method m : pluginClass.getMethods()) {
                if (m.getName().equals("getItem") && m.getParameterCount() == 2
                        && m.getParameterTypes()[1] == String.class
                        && !m.getParameterTypes()[0].equals(String.class)) {
                    this.getItemMethod = m;
                } else if (m.getName().equals("getMMOItem") && m.getParameterCount() == 2
                        && m.getParameterTypes()[1] == String.class
                        && !m.getParameterTypes()[0].equals(String.class)) {
                    this.getMMOItemMethod = m;
                } else if (m.getName().equals("getTypes") && m.getParameterCount() == 0) {
                    this.getTypesMethod = m;
                } else if (m.getName().equals("getTemplates") && m.getParameterCount() == 0) {
                    this.getTemplatesMethod = m;
                }
            }
            initialized = true;
        }
    }

    private Object getMMOPluginInstance() throws Exception {
        if (pluginField == null) {
            Class<?> mmoItemsClass = Class.forName("net.Indyuce.mmoitems.MMOItems");
            pluginField = mmoItemsClass.getField("plugin");
        }
        Object instance = pluginField.get(null);
        ensureInitialized(instance);
        return instance;
    }

    /**
     * Retrieves an ItemStack generated by MMOItems by Type and ID.
     */
    public ItemStack getItem(String typeName, String id) {
        if (!isAvailable() || typeName == null || id == null) {
            return null;
        }

        try {
            Object mmoPlugin = getMMOPluginInstance();
            if (mmoPlugin == null) {
                return null;
            }

            Object typeObj = resolveType(mmoPlugin, typeName);
            if (typeObj == null) {
                return null;
            }

            if (getItemMethod != null && getItemMethod.getParameterTypes()[0].isAssignableFrom(typeObj.getClass())) {
                Object result = getItemMethod.invoke(mmoPlugin, typeObj, id.toUpperCase());
                if (result instanceof ItemStack is) {
                    return is.clone();
                }
            }

            if (getMMOItemMethod != null && getMMOItemMethod.getParameterTypes()[0].isAssignableFrom(typeObj.getClass())) {
                Object mmoItem = getMMOItemMethod.invoke(mmoPlugin, typeObj, id.toUpperCase());
                if (mmoItem != null) {
                    Method newBuilderMethod = mmoItem.getClass().getMethod("newBuilder");
                    Object builder = newBuilderMethod.invoke(mmoItem);
                    if (builder != null) {
                        Method buildMethod = builder.getClass().getMethod("build");
                        Object built = buildMethod.invoke(builder);
                        if (built instanceof ItemStack is) {
                            return is.clone();
                        }
                    }
                }
            }
        } catch (Throwable t) {
            plugin.getLogger().warning("Error generating MMOItem (" + typeName + ":" + id + "): " + t.getMessage());
        }

        return null;
    }

    private Object resolveType(Object mmoPlugin, String typeName) {
        try {
            if (getTypesMethod != null) {
                Object typesManager = getTypesMethod.invoke(mmoPlugin);
                if (typesManager != null) {
                    Method getMethod = typesManager.getClass().getMethod("get", String.class);
                    Object typeObj = getMethod.invoke(typesManager, typeName.toUpperCase());
                    if (typeObj != null) {
                        return typeObj;
                    }
                }
            }
        } catch (Exception ignored) {
        }

        try {
            Class<?> typeClass = Class.forName("net.Indyuce.mmoitems.api.Type");
            Method getMethod = typeClass.getMethod("get", String.class);
            return getMethod.invoke(null, typeName.toUpperCase());
        } catch (Exception ignored) {
        }

        return null;
    }

    /**
     * Lists all registered MMOItems Types (cached for 30s for zero-lag tab-completion).
     */
    public List<String> getTypes() {
        if (!isAvailable()) {
            return Collections.emptyList();
        }

        long now = System.currentTimeMillis();
        if (!cachedTypes.isEmpty() && (now - cachedTypesTimestamp) < CACHE_TTL_MS) {
            return cachedTypes;
        }

        List<String> list = new ArrayList<>();
        try {
            Object mmoPlugin = getMMOPluginInstance();
            if (mmoPlugin != null && getTypesMethod != null) {
                Object typesManager = getTypesMethod.invoke(mmoPlugin);
                Method getAllMethod = typesManager.getClass().getMethod("getAll");
                Object collection = getAllMethod.invoke(typesManager);

                if (collection instanceof Iterable<?> iterable) {
                    Method getIdMethod = null;
                    for (Object obj : iterable) {
                        if (getIdMethod == null) {
                            getIdMethod = obj.getClass().getMethod("getId");
                        }
                        Object id = getIdMethod.invoke(obj);
                        if (id != null) {
                            list.add(id.toString());
                        }
                    }
                }
            }
        } catch (Throwable ignored) {
        }

        cachedTypes = Collections.unmodifiableList(list);
        cachedTypesTimestamp = now;
        return cachedTypes;
    }

    /**
     * Lists registered item template IDs for a given type (cached for 30s).
     */
    public List<String> getTemplateIds(String typeName) {
        if (!isAvailable() || typeName == null) {
            return Collections.emptyList();
        }

        long now = System.currentTimeMillis();
        String upperType = typeName.toUpperCase();
        if ((now - cachedTemplatesTimestamp) < CACHE_TTL_MS && cachedTemplateIds.containsKey(upperType)) {
            return cachedTemplateIds.get(upperType);
        }
        if ((now - cachedTemplatesTimestamp) >= CACHE_TTL_MS) {
            cachedTemplateIds.clear();
            cachedTemplatesTimestamp = now;
        }

        List<String> list = new ArrayList<>();
        try {
            Object mmoPlugin = getMMOPluginInstance();
            Object typeObj = resolveType(mmoPlugin, upperType);
            if (typeObj == null || getTemplatesMethod == null) {
                return list;
            }

            Object templatesManager = getTemplatesMethod.invoke(mmoPlugin);
            for (Method m : templatesManager.getClass().getMethods()) {
                if ((m.getName().equals("getTemplates") || m.getName().equals("collectTemplates"))
                        && m.getParameterCount() == 1
                        && m.getParameterTypes()[0].isAssignableFrom(typeObj.getClass())) {
                    Object result = m.invoke(templatesManager, typeObj);
                    if (result instanceof Iterable<?> iterable) {
                        Method getIdMethod = null;
                        for (Object template : iterable) {
                            try {
                                if (getIdMethod == null) {
                                    getIdMethod = template.getClass().getMethod("getId");
                                                                }
                                Object id = getIdMethod.invoke(template);
                                if (id != null) {
                                    list.add(id.toString());
                                }
                            } catch (Exception ignored) {
                            }
                        }
                    }
                    break;
                }
            }
        } catch (Throwable ignored) {
        }

        List<String> unmodifiable = Collections.unmodifiableList(list);
        cachedTemplateIds.put(upperType, unmodifiable);
        return unmodifiable;
    }
}
